"""Finalize the manuscript reference list (APA 7): add missing author initials from Crossref,
drop uncited entries, repair typography, sort alphabetically, and splice into the manuscript.

Input : docs/paper/references-apa.md (generated by build_apa_refs.py)
Output: docs/paper/references-apa.md (rewritten) and the References section of manuscript-draft.md
"""
import json, re, sys, unicodedata, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APA = ROOT / "docs/paper/references-apa.md"
MS = ROOT / "docs/paper/manuscript-draft.md"
CACHE = ROOT / "experiments/results/final-v8/crossref_authors.json"

DROP = ("Wang, Z., Du, Y., Zhang, Y., & Fang, M. (2023). MACCA", "Zhang, Y., Lyu, Y., Jo, S., & Yang, Y. (2025). Adaptive Deadlock", "Sharma, R. K.", "Van Hamme, T.")
MANUAL = {
    "Kaufmann": "Kaufmann, E., Cappé, O., & Garivier, A. (2012). On Bayesian upper confidence bounds for bandit problems. Proceedings of the 15th International Conference on Artificial Intelligence and Statistics, PMLR 22, 592–600. https://proceedings.mlr.press/v22/kaufmann12.html",
    "Kitchenham": "Kitchenham, B., & Charters, S. (2007). Guidelines for performing systematic literature reviews in software engineering (EBSE Technical Report EBSE-2007-01). Keele University and Durham University.",
    "Wu, Q., Bansal": "Wu, Q., Bansal, G., Zhang, J., Wu, Y., Li, B., Zhu, E., Jiang, L., Zhang, X., Zhang, S., Liu, J., Awadallah, A. H., White, R. W., Burger, D., & Wang, C. (2024a). AutoGen: Enabling next-gen LLM applications via multi-agent conversations. First Conference on Language Modeling (COLM 2024).",
    "Wu, Y., Roesner": "Wu, Y., Roesner, F., Kohno, T., & Zhang, N. (2024b). IsolateGPT: An execution isolation architecture for LLM-based agentic systems. Network and Distributed System Security (NDSS) Symposium 2025. https://arxiv.org/abs/2403.04960",
    "Zhou, S., Xu": "Zhou, S., Xu, F. F., Zhu, H., Zhou, X., Lo, R., Sridhar, A., Cheng, X., Ou, T., Bisk, Y., Fried, D., Alon, U., & Neubig, G. (2024). WebArena: A realistic web environment for building autonomous agents. The Twelfth International Conference on Learning Representations (ICLR 2024).",
    "Liu, Y., Jia, Y., Geng": "Liu, Y., Jia, Y., Geng, R., Jia, J., & Gong, N. Z. (2024). Formalizing and benchmarking prompt injection attacks and defenses. 33rd USENIX Security Symposium.",
}


def initials(given):
    parts = re.split(r"[\s]+", given.strip())
    out = []
    for p in parts:
        if not p:
            continue
        if "-" in p:
            out.append("-".join(x[0] + "." for x in p.split("-") if x))
        elif p.endswith("."):
            out.append(p)
        else:
            out.append(p[0] + ".")
    return " ".join(out)


def crossref_authors(doi, cache):
    if doi in cache:
        return cache[doi]
    url = "https://api.crossref.org/works/" + doi
    req = urllib.request.Request(url, headers={"User-Agent": "GUIDE-refs/1.0 (mailto:shafin@example.com)"})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            msg = json.loads(r.read())["message"]
        auth = [(a.get("family", ""), a.get("given", "")) for a in msg.get("author", []) if a.get("family")]
    except Exception as e:  # noqa
        print("crossref fail", doi, e, file=sys.stderr)
        auth = []
    cache[doi] = auth
    return auth


def fmt_authors(auth):
    names = [f"{f}, {initials(g)}".strip().rstrip(",") for f, g in auth]
    if len(names) == 1:
        return names[0]
    if len(names) > 20:
        return ", ".join(names[:19]) + ", . . . " + names[-1]
    return ", ".join(names[:-1]) + ", & " + names[-1]


def has_initials(head):
    return bool(re.search(r"[A-Z]\.(?:,| |$)", head)) and " et al" not in head


def sortkey(line):
    head = line.split("(", 1)[0]
    s = unicodedata.normalize("NFKD", head).encode("ascii", "ignore").decode().lower()
    s = re.sub(r"[^a-z, ]", "", s)
    y = re.search(r"\((\d{4}[a-z]?)\)", line)
    return (s, y.group(1) if y else "")


UPGRADE = {
    "Debenedetti, E., Shumailov": "10.1109/satml68715.2026.00040",
    "Debenedetti, E., Zhang, J., Balunović": "10.52202/079017-2636",
    "Zhan, Q., Liang": "10.18653/v1/2024.findings-acl.624",
    "Greshake, K.": "10.1145/3605764.3623985",
}


def upgrade(l, cache):
    for k, doi in UPGRADE.items():
        if l.startswith(k) and "arXiv preprint" in l:
            msg_url = "https://api.crossref.org/works/" + doi
            key = "full:" + doi
            if key not in cache:
                req = urllib.request.Request(msg_url, headers={"User-Agent": "GUIDE-refs/1.0 (mailto:shafin@example.com)"})
                with urllib.request.urlopen(req, timeout=20) as r:
                    m = json.loads(r.read())["message"]
                cache[key] = {"auth": [(a.get("family", ""), a.get("given", "")) for a in m["author"]],
                              "title": m["title"][0], "venue": m["container-title"][0],
                              "year": m["issued"]["date-parts"][0][0], "page": m.get("page", "")}
            c = cache[key]
            pages = ", " + c["page"].replace("-", "–") if c["page"] else ""
            return f"{fmt_authors(c['auth'])} ({c['year']}). {c['title']}. {c['venue']}{pages}. https://doi.org/{doi}"
    return l


def main():
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    lines = [l[2:].rstrip("\n") for l in APA.read_text().splitlines(keepends=True) if l.startswith("- ")]
    out = []
    for l in lines:
        if l.startswith(DROP):
            continue
        l = l.replace("––", "–").replace("Peign{\\'e}", "Peigné").replace("\\&", "&")
        l = re.sub(r"Research1\.", "Research.", l)
        l = l.replace("Pasupuleti, Allala, Bayyavarapu, R. K. V., & Tyagi (2026)", "Pasupuleti, V., Allala, S. R., Bayyavarapu, S. R. K. V., & Tyagi, S. (2026)")
        l = l.replace("Van hamme,", "Van Hamme,").replace(" -- ", ": ")
        m = re.match(r"(.+?)\s*\((\d{4}[a-z]?)\)\.\s*(.*)", l)
        head = m.group(1)
        l = upgrade(l, cache)
        m = re.match(r"(.+?)\s*\((\d{4}[a-z]?)\)\.\s*(.*)", l)
        head = m.group(1)
        manual = next((v for k, v in MANUAL.items() if l.startswith(k)), None)
        if manual:
            out.append(manual)
            continue
        if not has_initials(head):
            doi = re.search(r"https://doi\.org/(\S+)", l)
            auth = crossref_authors(doi.group(1), cache) if doi else []
            if auth:
                l = f"{fmt_authors(auth)} ({m.group(2)}). {m.group(3)}"
            else:
                print("NO AUTHORS RESOLVED:", l[:90], file=sys.stderr)
        out.append(l)
    CACHE.write_text(json.dumps(cache, indent=1))
    out.sort(key=sortkey)
    APA.write_text("# References (APA 7th)\n\n" + "".join(f"- {l}\n" for l in out))
    ms = MS.read_text()
    a = ms.index("## References")
    b = ms.index("\n## Supplementary material")
    sec = ("## References\n\nReferences are listed alphabetically by first author surname following APA 7th edition.\n\n"
           + "\n\n".join(out) + "\n")
    MS.write_text(ms[:a] + sec + ms[b:])
    print("references written:", len(out))


main()
