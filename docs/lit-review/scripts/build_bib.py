def esc(s: str) -> str:
    return (s or "").replace("{", "").replace("}", "").replace("&", r"\&").replace("%", r"\%")


def entry(key, title, authors, year, venue, doi, arxiv, note):
    kind = "misc" if (not venue or "arxiv" in venue.lower()) else "inproceedings"
    f = [f"  title = {{{{{esc(title)}}}}}"]
    if authors:
        f.append(f"  author = {{{esc(' and '.join(a.strip() for a in authors.split(';') if a.strip()))}}}")
    if year:
        f.append(f"  year = {{{year}}}")
    if kind == "inproceedings":
        f.append(f"  booktitle = {{{esc(venue)}}}")
    if doi and "arxiv" not in doi.lower():
        f.append(f"  doi = {{{doi}}}")
    if arxiv:
        f.append(f"  eprint = {{{arxiv}}}"); f.append("  archivePrefix = {arXiv}")
    f.append(f"  note = {{{esc(note)}}}")
    return f"@{kind}{{{key},\n" + ",\n".join(f) + "\n}\n"


def main() -> None:
    out = ["% Generated by docs/lit-review/scripts/build_bib.py -- verification status in each `note`.\n"
           "% Entries marked UNVERIFIED or preprint must be checked on the publisher page before citation.\n"
           "% Known gaps: Crossref-sourced entries carry family names only, and journal articles are typed\n"
           "% @inproceedings; complete given names and switch to @article when formatting for the journal.\n"]
    for r in csv.DictReader((OUT / "must-check.csv").open()):
        arx = r["identifier"][6:] if r["identifier"].startswith("arxiv:") else ""
        doi = r["found_doi"] or (r["identifier"][4:] if r["identifier"].startswith("doi:") else "")
        out.append(entry(r["key"], r["found_title"], r["found_authors"], r["found_year"], r["found_venue"],
                         doi, arx, f"{r['status']}; venue check: {r['venue_check']}"))
    recs = {json.loads(l)["id"]: json.loads(l) for l in (D / "records.jsonl").open()}
    have = {m["identifier"][6:] for m in csv.DictReader((OUT / "must-check.csv").open()) if m["identifier"].startswith("arxiv:")}
    for rid, k in CORE_KEYS.items():
        r = recs[rid]
        if r.get("arxiv") and r["arxiv"] in have:
            continue
        out.append(entry(k, r["title"], r.get("authors", ""), r.get("year"), r.get("venue", ""), r.get("doi", ""),
                         r.get("arxiv", ""), "metadata from search record (OpenAlex/arXiv/S2); preprint unless venue given"))
    (ROOT / "references.bib").write_text("\n".join(out))
    print(len(out) - 1, "entries")


if __name__ == "__main__":
    main()
